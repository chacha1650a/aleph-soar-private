"""Generate tool adapters from repo-owned skills and roles; never edit global config."""

import argparse
import json
from pathlib import Path, PurePosixPath
import re
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "ai/generated-assets.json"
PREFIXES = (".claude/skills/", ".claude/agents/", ".codex/agents/")


def read_role(path):
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not match:
        raise ValueError(f"Invalid role frontmatter: {path}")
    metadata = yaml.safe_load(match[1])
    if not isinstance(metadata, dict):
        raise ValueError(f"Role metadata must be an object: {path}")
    name = metadata.get("name")
    description = metadata.get("description")
    if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name != path.stem:
        raise ValueError(f"Role name must match its filename: {path}")
    if not isinstance(description, str) or not description.strip() or not match[2].strip():
        raise ValueError(f"Role description and instructions are required: {path}")
    return name, description, match[2]


def expected_assets(root):
    assets = {}
    for source in sorted((root / ".agents/skills").rglob("*")):
        if source.is_file():
            relative = source.relative_to(root / ".agents/skills").as_posix()
            assets[f".claude/skills/{relative}"] = source.read_bytes()
    for source in sorted((root / "ai/roles").glob("*.md")):
        name, description, body = read_role(source)
        assets[f".claude/agents/{name}.md"] = source.read_bytes()
        config = "# Generated by tools/sync_ai_assets.py; edit ai/roles instead.\n"
        for key, value in (("name", name), ("description", description), ("developer_instructions", body)):
            config += f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
        assets[f".codex/agents/{name}.toml"] = config.encode("utf-8")
    if not assets:
        raise ValueError("No canonical AI assets found.")
    return assets


def target_path(root, relative):
    path = PurePosixPath(relative)
    if path.is_absolute() or ".." in path.parts or not relative.startswith(PREFIXES):
        raise ValueError(f"Invalid managed asset path: {relative}")
    target = root / relative
    if not target.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Managed asset escapes repository: {relative}")
    return target


def synchronize(root=ROOT, check=False):
    assets = expected_assets(root)
    manifest_path = root / MANIFEST
    previous = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else []
    if not isinstance(previous, list) or not all(isinstance(item, str) for item in previous):
        raise ValueError("Invalid generated-assets manifest.")
    for relative in set(previous) | set(assets):
        target_path(root, relative)
    obsolete = set(previous) - set(assets)
    changed = [relative for relative, content in assets.items()
               if not target_path(root, relative).is_file() or target_path(root, relative).read_bytes() != content]
    manifest_bytes = (json.dumps(sorted(assets), indent=2) + "\n").encode("utf-8")
    manifest_changed = not manifest_path.exists() or manifest_path.read_bytes() != manifest_bytes
    if check:
        differences = changed + sorted(obsolete) + ([MANIFEST] if manifest_changed else [])
        if differences:
            raise ValueError("Generated assets are out of sync: " + ", ".join(differences))
        return len(assets)
    for relative in changed:
        target = target_path(root, relative)
        if target.exists() and relative not in previous:
            raise ValueError(f"Refusing to overwrite an unmanaged file: {relative}")
    for relative, content in assets.items():
        target = target_path(root, relative)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    for relative in obsolete:
        target_path(root, relative).unlink(missing_ok=True)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_bytes(manifest_bytes)
    return len(assets)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        count = synchronize(check=args.check)
    except (ValueError, OSError, yaml.YAMLError) as error:
        print(str(error), file=sys.stderr)
        return 1
    print(f"AI assets {'verified' if args.check else 'generated'}: {count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
